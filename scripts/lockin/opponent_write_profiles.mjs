import { fileURLToPath } from "node:url";
// profiles.json -> lib/lockin/managerProfiles.js (committed constants). node write_profiles.mjs
import fs from "node:fs";
import path from "node:path";
const D = process.env.LOCKIN_CACHE_DIR || path.join(path.dirname(new URL(import.meta.url).pathname), "cache");
const WT = fileURLToPath(new URL("../../", import.meta.url)).replace(/\/$/, "");
const P = JSON.parse(fs.readFileSync(path.join(D, "profiles.json"), "utf8"));
const r = (x, d = 3) => (x == null ? null : Math.round(x * 10 ** d) / 10 ** d);
const prof = (p, weeks, seasons, shrinkage) => ({
  unknownLockedShare: r(p.unknownLockedShare),
  lockTiming: { earlyShare: r(p.earlyShare) },
  lockThreshold: { median: r(p.lockMedian, 1), vsForecast: r(p.vsForecast) },
  emptySlotRate: r(p.emptySlotRate),
  zeroRate: r(p.zeroRate),
  benchUse: r(p.benchUse),
  pointsVsRulePerSlot: r(p.pointsVsRulePerSlot, 2),
  weeks,
  seasons,
  shrinkage: r(shrinkage),
});
const league = prof(P.league, P.league.weeks, P.league.seasons, 0);
const managers = Object.fromEntries(Object.entries(P.managers).map(([o, m]) => [o, prof(m, m.weeks, m.seasons, m.shrinkage)]));
const v = P.validation;
const out = `/**
 * Fitted manager lock-in profiles. GENERATED by scripts/lockin/opponent_profiles.mjs on
 * ${new Date().toISOString().slice(0, 10)} from every completed lock-in week, 2022-2026 week 5 (the league has
 * been lock-in, game_mode 1, in all five seasons): ${P.league.weeks} team-weeks, ${Object.keys(managers).length} owners.
 * Recency half-life ${P.chosen.hl} weeks and credibility K ${P.chosen.K} team-weeks, chosen by predicting each
 * manager's 2026 values from <=2025 data (standardised MSE ${P.chosen.mse.toFixed(3)}, n ${P.chosen.n}).
 * Validation, weekly total predicted at week start on 2026 weeks 1-5 (n=${v.n}, fit on 2022-2025):
 * league profile MAE ${v.mae.league.toFixed(1)}, p10-p90 coverage ${v.coverage.league.toFixed(2)};
 * manager profile MAE ${v.mae.manager.toFixed(1)}, coverage ${v.coverage.manager.toFixed(2)};
 * rule only MAE ${v.mae.none.toFixed(1)}, coverage ${v.coverage.none.toFixed(2)}.
 * The manager profile did not beat the league profile, so the simulation uses league values
 * (USE_MANAGER_IN_SIM false); manager profiles are shown as description only.
 */
export const USE_MANAGER_IN_SIM = ${v.mae.manager < v.mae.league};
export const FITTED_LEAGUE = ${JSON.stringify(league, null, 1)};
export const FITTED_MANAGERS = ${JSON.stringify(managers, null, 1)};
export const FITTED_PARAMS = ${JSON.stringify({ halfLifeWeeks: P.chosen.hl, credibilityK: P.chosen.K, validation: v })};
`;
fs.writeFileSync(path.join(WT, "lib/lockin/managerProfiles.js"), out);
console.log("wrote", Object.keys(managers).length, "managers; use manager in sim:", v.mae.manager < v.mae.league);
